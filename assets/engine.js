    if (/(하지 마|하지마|말고|제외|금지|빼고|없이|단,|반드시|조건|제한|까지만|이내|초과하지|do not|avoid|must|only|without)/i.test(t)) score.constraint += 12;
    if (/(톤|말투|존댓말|반말|어조|스타일|tone)/i.test(t)) score.constraint += 4;
