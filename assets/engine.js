    if (/(왜|목적|배경|상황|문제|이유|주제는|because|goal|background)/i.test(t)) score.context += 3;
    if (/(\d{2,}|원|명|개|시간|%|년|월|일)/.test(t)) score.context += 2;
    score.context = Math.min(score.context, 20);
