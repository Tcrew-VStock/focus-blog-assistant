  function buildPrompt(cfg) {
    cfg = cfg || {};
    var domain = domainById(cfg.domainId);
    var mode = modeOf(cfg.mode);
    var task = null;
    for (var i = 0; i < domain.tasks.length; i++) if (domain.tasks[i].id === cfg.taskId) task = domain.tasks[i];
    if (!task) task = domain.tasks[0];

    var target = cfg.target || 'universal';
    /* 이미지 AI 타겟은 시각 분야에서만 적용한다(금융·코딩 텍스트가 이미지 프롬프트로 바뀌지 않도록) */
    if (target === 'image' && !domain.isVisual) target = 'universal';
    var fw = resolveFramework(cfg.framework, domain, target);
    var intent = parseIntent(String((cfg.values || {})[domain.primary] || ''));

    var result;
    if (target === 'image' || (domain.isVisual && target === 'universal')) {
      result = buildImagePrompt(cfg, domain, task, mode.id);
      fw = 'creative';
    } else {
      var m = buildModel(cfg, domain, task);
      var sections = sectionsFor(fw, m);
      result = { prompt: fixJosa(renderTarget(sections, cfg, m)), sections: sections };
    }
    if (result.prompt && !result.image) result.prompt = fixJosa(result.prompt);

    var vars = extractVars(result.prompt);
    return {
      prompt: result.prompt,
      sections: result.sections,
      vars: vars,
      domain: domain,
      task: task,
      framework: fw,
      target: target,
      mode: mode,
      intent: intent,
      image: !!result.image
    };
  }

  function extractVars(text) {
    var out = [], re = /\{\{([^{}\n]{1,40})\}\}/g, m;
    while ((m = re.exec(text))) {
      var name = m[1].trim();
      if (out.indexOf(name) === -1) out.push(name);
    }
    return out;
  }

  function fillVars(text, map) {
    return text.replace(/\{\{([^{}\n]{1,40})\}\}/g, function (whole, name) {
      var key = name.trim();
      var val = map && map[key] != null ? String(map[key]) : '';
      return val.trim() ? val : whole;
    });
  }

