    if (/(열|칸|컬럼|항목|단계|장면|순서|구조|template|예시)/i.test(t)) score.format += 4;
    if (/\n/.test(t)) score.format += 3;
    score.format = Math.min(score.format, 20);
    notes.format = score.format >= 11 ? '' : '결과물의 모양(표, 목록, 분량, 구조)이 지정되지 않았습니다.';

