  function scoreAxis(axis, t) {
    var items = axis.criteria.map(function (c) { return { label: c.label, ok: c.test(t), fix: c.fix }; });
    var ok = items.filter(function (i) { return i.ok; }).length;
    var score = Math.round(axis.max * ok / items.length);
    return { key: axis.key, label: axis.label, max: axis.max, score: score, items: items, why: axis.why };
  }

  function diagnose(text) {
    var t = String(text || '').trim();
    var axes = AXES.map(function (a) { return scoreAxis(a, t); });
    var total = axes.reduce(function (s, a) { return s + a.score; }, 0);
    var grade = total >= 85 ? '전문가급' : total >= 65 ? '양호' : total >= 40 ? '보통' : '초보';
    var gaps = [];
    axes.forEach(function (a) {
      a.items.forEach(function (i) {
        if (!i.ok) gaps.push({ axis: a.label, item: i.label, fix: i.fix, why: a.why });
      });
    });
    var missing = axes.filter(function (a) { return a.score < a.max * 0.6; }).map(function (a) {
      var miss = a.items.filter(function (i) { return !i.ok; }).map(function (i) { return i.label; });
      return {
        key: a.key, label: a.label, score: a.score, max: a.max,
        note: '빠진 항목: ' + miss.join(', '),
        tip: a.why
      };
    });
    var intent = parseIntent(t);
    return {
      score: total,
      grade: grade,
      length: t.length,
      axes: axes.map(function (a) { return { key: a.key, label: a.label, score: a.score, max: a.max }; }),
      details: axes.map(function (a) { return { key: a.key, label: a.label, score: a.score, max: a.max, items: a.items }; }),
      gaps: gaps,
      missing: missing,
      signals: intentSummary(intent),
      strengths: axes.filter(function (a) { return a.score >= a.max * 0.8; }).map(function (a) { return a.label; })
    };
  }

