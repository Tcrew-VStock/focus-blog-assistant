    if (/\d+\s*(개|가지|문장|줄|단계|자|페이지|분|초)/.test(t)) score.instruction += 3;
    score.instruction = Math.min(score.instruction, 20);
    notes.instruction = score.instruction >= 12 ? '' : '무엇을 어떤 순서로 할지 지시가 적습니다. 동사로 단계를 나눠 보세요.';

