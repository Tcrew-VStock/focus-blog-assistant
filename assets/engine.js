  function modeOf(id) { return pick(MODES, id || 'standard'); }

  function buildModel(cfg, domain, task) {
    var vals = cfg.values || {};
    var mode = modeOf(cfg.mode);
    var pro = mode.id === 'pro';
    var V = function (id) {
      var f = null;
      for (var i = 0; i < domain.fields.length; i++) if (domain.fields[i].id === id) f = domain.fields[i];
      var raw = String(vals[id] == null ? '' : vals[id]).trim();
      if (raw) return raw;
      return '{{' + (f ? f.v : id) + '}}';
    };

    var objective = (task.objective || []).map(function (s) {
      return s.replace(/\{\{(\w+)\}\}/g, function (_, k) { return V(k); });
    });

    var primaryRaw = String(vals[domain.primary] == null ? '' : vals[domain.primary]).trim();
    /* 의도 신호는 사용자가 직접 쓴 주제 입력에서만 읽는다(안내문·시세 블록이 섞이지 않도록) */
    var intent = parseIntent(primaryRaw);
    var signals = intentSummary(intent);

    var context = [];
    domain.fields.forEach(function (f) {
      if (f.id === domain.primary) return;
      var raw = String(vals[f.id] == null ? '' : vals[f.id]).trim();
      if (!raw) return;
      context.push('- ' + f.label + ': ' + raw.replace(/\n/g, ' / '));
    });
    if (cfg.audience) context.push('- 대상 독자/사용자: ' + cfg.audience);
    else if (domain.audienceDefault) context.push('- 대상 독자/사용자: ' + domain.audienceDefault);
    if (cfg.marketBlock) {
      context.push('- 시장 데이터(아래 블록은 실제 조회값이며 임의로 바꾸지 않는다):');
      context.push(cfg.marketBlock.trim());
    }
    if (cfg.extraContext) {
      context.push('- 참고할 원문 요청:');
      context.push(cfg.extraContext.trim());
    }

    var tone = pick(TONES, cfg.tone);
    var depth = pick(DEPTHS, cfg.depth);
    var lang = pick(LANGS, cfg.lang);
    var fmt = pick(FORMATS, cfg.format);

    var styleLine = '- 문체: ' + (domain.style || '명확하고 간결한 문장');
    if (cfg.styleNote) styleLine += ' / ' + cfg.styleNote;

    var formatLines = [];
    formatLines.push('- 답변 언어: ' + lang.hint);
    if (fmt && fmt.id !== 'auto') formatLines.push('- 출력 형식: ' + fmt.label + ' — ' + fmt.hint);
    else if (task.formatHint) formatLines.push('- 출력 형식: ' + task.formatHint);
    else formatLines.push('- 출력 형식: ' + (domain.formatDefault || '읽기 쉬운 마크다운. 핵심은 소제목과 목록으로 구조화한다.'));
    if (cfg.length) formatLines.push('- 분량: ' + cfg.length);
    formatLines.push('- 추론 깊이: ' + depth.hint);
    if (cfg.target === 'perplexity') formatLines.push('- 답변 끝에 출처 목록을 번호와 함께 붙이고, 문장 안에는 [1] 형태로 인용 번호를 단다.');

    var constraintLines = [];
    (cfg.forbid || []).forEach(function (id) {
      var f = pick(FORBIDS, id);
      if (f && f.text) constraintLines.push('- ' + f.text);
    });
    if (intent.numbers.length) {
      constraintLines.push('- 입력에 명시된 수치(' + intent.numbers.join(', ') + ')는 그대로 쓰고, 새로운 수치를 만들어 덧붙이지 않는다.');
    }
    if (intent.constraints.length) {
      constraintLines.push('- 입력에 담긴 제약을 모두 지킨다: ' + intent.constraints.map(function (c) { return '"' + c + '"'; }).join(' / '));
    }
    if (intent.tech.length) {
      constraintLines.push('- 입력에서 확인된 기술·도구(' + intent.tech.join(', ') + ')를 전제로 답한다. 다른 도구를 임의로 바꾸지 않는다.');
    }
    if (intent.audience.length && !cfg.audience) {
      constraintLines.push('- 입력에 언급된 대상(' + intent.audience.join(', ') + ')의 눈높이와 상황에 맞춘다.');
    }
    if (intent.quoted.length) {
      constraintLines.push('- 사용자가 직접 지정한 표현(' + intent.quoted.map(function (q) { return '"' + q + '"'; }).join(', ') + ')은 다른 말로 바꾸지 않는다.');
    }
    if (cfg.customForbid && cfg.customForbid.trim()) {
      cfg.customForbid.split(/\n+/).forEach(function (line) {
        if (line.trim()) constraintLines.push('- ' + line.trim());
      });
    }
    if (!constraintLines.length) constraintLines.push('- 확인하지 못한 정보는 추정하지 않고 [확인 필요]로 표시한다.');

    var qualityLines = (task.quality || []).map(function (q) { return '- ' + q; });

    var model = {
      role: domain.role,
      objective: objective,
      steps: (task.steps || []).map(function (s, i) { return (i + 1) + '. ' + s; }),
      context: context,
      styleLine: styleLine,
      toneLine: '- 톤앤매너: ' + tone.label + ' — ' + tone.hint,
      langLine: '- 답변 언어: ' + lang.hint,
      depthLine: '- 추론 깊이: ' + depth.hint,
      constraint: constraintLines,
      format: formatLines,
      quality: qualityLines,
      audience: cfg.audience || domain.audienceDefault || '',
      tone: tone,
      depth: depth,
      lang: lang,
      fmt: fmt,
      task: task,
      domain: domain,
      mode: mode,
      pro: pro,
      intent: intent,
      signals: signals
    };
    return model;
  }

