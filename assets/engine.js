    // 지침
    var verbs = (t.match(/(작성|정리|분석|비교|추천|설명|요약|만들|만들어|써|써줘|넣|넣어|짜|짜줘|알려|제안|검토|평가|나눠|뽑아|뽑|도출|설계|계획|번역|확인|골라|작성해|적어)/g) || []).length;
    if (verbs >= 1) score.instruction += 6;
