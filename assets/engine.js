  /* 한국어 조사 자동 교정: "웹앱을(를)" 같은 표기를 받침에 맞게 고른다. */
  var LATIN_BATCHIM = 'lmrnLMNR';
  function hasBatchim(word) {
    if (!word) return false;
    var ch = word.slice(-1);
    var code = ch.charCodeAt(0);
    if (code >= 0xAC00 && code <= 0xD7A3) return (code - 0xAC00) % 28 !== 0;
    if (/[0-9]/.test(ch)) return '013678'.indexOf(ch) !== -1;
    if (LATIN_BATCHIM.indexOf(ch) !== -1) return true;
    return false;
  }
  function lastJong(word) {
    if (!word) return 0;
    var code = word.charCodeAt(word.length - 1);
    if (code >= 0xAC00 && code <= 0xD7A3) return (code - 0xAC00) % 28;
    return -1;
  }
  function fixJosa(text) {
    return String(text).replace(/([가-힣A-Za-z0-9)\]}"'])(을\(를\)|이\(가\)|은\(는\)|와\(과\)|으로\(로\))/g, function (m, prev, suf) {
      var bat = hasBatchim(prev);
      if (suf === '을(를)') return prev + (bat ? '을' : '를');
      if (suf === '이(가)') return prev + (bat ? '이' : '가');
      if (suf === '은(는)') return prev + (bat ? '은' : '는');
      if (suf === '와(과)') return prev + (bat ? '과' : '와');
      return prev + ((bat && lastJong(prev) !== 8) ? '으로' : '로');
    });
  }

  function joinLines(parts) {
    var out = [];
    parts.forEach(function (p) {
      if (p === null || p === undefined) return;
      if (Object.prototype.toString.call(p) === '[object Array]') {
        p.forEach(function (x) { if (x !== null && x !== undefined && String(x).length) out.push(String(x)); });
      } else if (String(p).length) out.push(String(p));
    });
    return out.join('\n');
  }

